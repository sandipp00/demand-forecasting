"""Assemble reports/REPORT.md from the metrics and figures produced by the pipeline."""
from __future__ import annotations

import pandas as pd

from . import config


def _md_table(df: pd.DataFrame, floatfmt="{:.3f}") -> str:
    df = df.copy()
    for c in df.columns:
        if pd.api.types.is_float_dtype(df[c]):
            df[c] = df[c].map(lambda v: floatfmt.format(v) if pd.notna(v) else "")
    cols = [str(df.index.name or "")] + [str(c) for c in df.columns]
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for idx, row in df.iterrows():
        lines.append("| " + " | ".join([str(idx)] + [str(v) for v in row.values]) + " |")
    return "\n".join(lines)


def _money(v, cur):
    return f"{cur} {v/1e6:,.2f}M" if abs(v) >= 1e6 else f"{cur} {v:,.0f}"


